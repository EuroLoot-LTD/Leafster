import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import supertest from "supertest";
import { createApp } from "../server/app.js";
import { run, ffmpegPath } from "../server/media.js";
process.env.NODE_ENV = "test";
process.env.LEAFSTER_TEST_AUTH = "true";

test("real local video pipeline, authorisation, social persistence and account lifecycle", async () => {
  const dataDir = fs.mkdtempSync(path.join(os.tmpdir(), "leafster-api-"));
  const site = createApp({ dataDir });
  const a = supertest.agent(site.app),
    b = supertest.agent(site.app),
    anon = supertest.agent(site.app);
  async function login(agent: any, email: string, handle: string) {
    let s = await agent.get("/api/session").expect(200);
    let l = await agent
      .post("/api/test/login")
      .set("x-csrf-token", s.body.csrfToken)
      .send({ email })
      .expect(200);
    await agent
      .post("/api/onboarding")
      .set("x-csrf-token", l.body.csrfToken)
      .send({ name: handle, handle, adultConfirmed: true })
      .expect(200);
    return l.body.csrfToken;
  }
  const aCsrf = await login(a, "one@example.test", "creator_one");
  const bCsrf = await login(b, "two@example.test", "creator_two");
  const aSession = (await a.get("/api/session")).body;
  assert.equal(aSession.user.handle, "creator_one");
  await b.get("/api/moderation").expect(403);
  await a.post("/api/leaves").send({ body: "Missing CSRF" }).expect(403);
  await a
    .post("/api/leaves")
    .set("x-csrf-token", aCsrf)
    .set("origin", "https://attacker.example")
    .send({ body: "bad origin" })
    .expect(403);
  await a
    .post("/api/uploads")
    .set("x-csrf-token", aCsrf)
    .field("title", "Invalid video")
    .attach("file", Buffer.from("not a real video"), {
      filename: "bad.mp4",
      contentType: "video/mp4",
    })
    .expect(400);
  const source = path.join(dataDir, "fixture.mp4");
  await run(ffmpegPath, [
    "-y",
    "-v",
    "error",
    "-f",
    "lavfi",
    "-i",
    "testsrc2=size=320x180:rate=10",
    "-t",
    "2",
    "-c:v",
    "libx264",
    "-pix_fmt",
    "yuv420p",
    source,
  ]);
  const uploaded = await a
    .post("/api/uploads")
    .set("x-csrf-token", aCsrf)
    .field("title", "Original engineering test clip")
    .field(
      "description",
      "Generated by the integration test, not a public creator upload.",
    )
    .field("visibility", "public")
    .attach("file", source)
    .expect(202);
  const vid = uploaded.body.video.id;
  for (let n = 0; n < 150; n++) {
    const r = await a.get(`/api/videos/${vid}`);
    if (r.body.video.status === "ready") break;
    if (r.body.video.status === "failed") assert.fail(r.body.video.error);
    await new Promise((r) => setTimeout(r, 100));
  }
  const watched = (await b.get(`/api/videos/${vid}`).expect(200)).body.video;
  assert.equal(watched.status, "ready");
  assert.ok(watched.duration >= 1.9);
  assert.ok(watched.thumbnailUrl);
  assert.ok(watched.playbackUrl);
  const search = await b.get("/api/videos?q=Original&sort=oldest").expect(200);
  assert.equal(search.body.videos.length, 1);
  await anon.get(watched.playbackUrl).set("range", "bytes=0-63").expect(206).expect("Content-Type",/video\/mp4/);
  await b
    .get(watched.playbackUrl)
    .set("range", "bytes=0-63")
    .expect(206)
    .expect("Content-Type", /video\/mp4/);
  await b
    .patch(`/api/videos/${vid}`)
    .set("x-csrf-token", bCsrf)
    .send({ title: "Stolen edit" })
    .expect(404);
  const reaction = await b
    .post(`/api/videos/${vid}/reaction`)
    .set("x-csrf-token", bCsrf)
    .send({ value: 1 })
    .expect(200);
  assert.equal(reaction.body.likes, 1);
  await b
    .post(`/api/channels/${watched.channel.id}/subscribe`)
    .set("x-csrf-token", bCsrf)
    .send({})
    .expect(200);
  await b
    .post(`/api/videos/${vid}/comments`)
    .set("x-csrf-token", bCsrf)
    .send({ body: "Public test comment" })
    .expect(201);
  await b
    .post(`/api/videos/${vid}/progress`)
    .set("x-csrf-token", bCsrf)
    .send({ seconds: 1, watchedSeconds: 1 })
    .expect(200);
  const h = await b.get("/api/history").expect(200);
  assert.equal(h.body.videos[0].progress, 1);
  const playlist = await b
    .post("/api/playlists")
    .set("x-csrf-token", bCsrf)
    .send({ title: "Saved test videos", visibility: "private" })
    .expect(201);
  await b
    .post(`/api/playlists/${playlist.body.playlist.id}/items`)
    .set("x-csrf-token", bCsrf)
    .send({ videoId: vid })
    .expect(200);
  await a.get(`/api/playlists/${playlist.body.playlist.id}`).expect(404);
  const leaf = await a
    .post("/api/leaves")
    .set("x-csrf-token", aCsrf)
    .send({ body: "A public development update.", videoId: vid })
    .expect(201);
  await b
    .post("/api/leaves")
    .set("x-csrf-token", bCsrf)
    .send({ body: "A public reply.", parentId: leaf.body.leaf.id })
    .expect(201);
  await b
    .post(`/api/leaves/${leaf.body.leaf.id}/like`)
    .set("x-csrf-token", bCsrf)
    .send({})
    .expect(200);
  const leaves = await b.get("/api/leaves").expect(200);
  assert.equal(leaves.body.leaves[0].replies.length, 1);
  assert.equal(leaves.body.leaves[0].likes, 1);
  const note = await b
    .post("/api/notes")
    .set("x-csrf-token", bCsrf)
    .send({
      targetType: "video",
      targetId: vid,
      body: "This is a test clip generated locally, rather than an actual creator video.",
      sources: ["https://example.com/context"],
    })
    .expect(201);
  assert.equal(note.body.note.status, "pending");
  await a
    .post(`/api/notes/${note.body.note.id}/rate`)
    .set("x-csrf-token", aCsrf)
    .send({ helpful: true })
    .expect(403);
  const report = await b
    .post("/api/reports")
    .set("x-csrf-token", bCsrf)
    .send({
      targetType: "video",
      targetId: vid,
      reason: "test-report",
      details: "Review queue test",
    })
    .expect(201);
  const studio = await a.get("/api/studio").expect(200);
  assert.equal(studio.body.analytics.subscribers, 1);
  assert.equal(studio.body.analytics.views, 1);
  assert.equal(studio.body.comments.length, 1);
  await a
    .patch(`/api/videos/${vid}`)
    .set("x-csrf-token", aCsrf)
    .send({ visibility: "private" })
    .expect(200);
  await b.get(watched.playbackUrl).expect(404);
  site.db
    .prepare("UPDATE users SET role='moderator' WHERE email=?")
    .run("two@example.test");
  const review = await b.get("/api/moderation").expect(200),
    reported = review.body.reports.find((r: any) => r.id === report.body.id);
  assert.match(reported.contentPreview, /Original engineering test clip/);
  assert.equal(reported.targetAuthorId, aSession.user.id);
  assert.ok(reported.mediaReviewUrl);
  await a.get(reported.mediaReviewUrl).expect(403);
  await anon.get(reported.mediaReviewUrl).expect(401);
  await b
    .get(reported.mediaReviewUrl)
    .expect(200)
    .expect("Content-Type", /video\/mp4/)
    .expect("Cache-Control", /no-store/);
  const image = path.join(dataDir, "story.jpg");
  await run(ffmpegPath, [
    "-y",
    "-v",
    "error",
    "-f",
    "lavfi",
    "-i",
    "color=c=orange:s=320x180",
    "-frames:v",
    "1",
    image,
  ]);
  const story = await a
    .post("/api/stories")
    .set("x-csrf-token", aCsrf)
    .field("caption", "Original development test image")
    .attach("file", image)
    .expect(201);
  await anon.get(story.body.story.mediaUrl).expect(401);
  await b
    .get(story.body.story.mediaUrl)
    .expect(200)
    .expect("Content-Type", /image\/jpeg/);
  site.db
    .prepare("UPDATE stories SET expires_at=? WHERE id=?")
    .run(new Date(Date.now() - 1000).toISOString(), story.body.story.id);
  await b.get(story.body.story.mediaUrl).expect(404);
  assert.equal((await a.get("/api/stories")).body.stories.length, 0);
  const sessions = await a.get("/api/account/sessions").expect(200);
  assert.equal(sessions.body.sessions.length, 1);
  assert.equal(sessions.body.sessions[0].current, true);
  const exported = await b.get("/api/account/export").expect(200);
  assert.equal(exported.body.profile.email, "two@example.test");
  assert.equal(exported.body.playlists.length, 1);
  await b
    .delete("/api/account")
    .set("x-csrf-token", bCsrf)
    .send({ confirm: "DELETE" })
    .expect(200);
  assert.equal((await b.get("/api/session")).body.user, null);
  await a
    .post("/api/auth/logout")
    .set("x-csrf-token", aCsrf)
    .send({})
    .expect(200);
  assert.equal((await a.get("/api/session")).body.user, null);
  site.close();
  fs.rmSync(dataDir, { recursive: true, force: true });
});

test("test authentication route is absent in normal development", async () => {
  delete process.env.LEAFSTER_TEST_AUTH;
  const dataDir = fs.mkdtempSync(path.join(os.tmpdir(), "leafster-normal-"));
  const site = createApp({ dataDir });
  const agent = supertest.agent(site.app);
  const csrf = (await agent.get("/api/session")).body.csrfToken;
  await agent
    .post("/api/test/login")
    .set("x-csrf-token", csrf)
    .send({ email: "intruder@example.test" })
    .expect(404);
  site.close();
  fs.rmSync(dataDir, { recursive: true, force: true });
  process.env.LEAFSTER_TEST_AUTH = "true";
});
